<?php

use Illuminate\Config\Repository;
use Illuminate\Filesystem\Filesystem;
use Laravel\Wayfinder\Console\GenerateCommand;
use Symfony\Component\Process\Process;

use function Illuminate\Filesystem\join_paths;

const GENERATED_HEADER = '// This file is auto-generated by Laravel Wayfinder.';

beforeEach(function () {
    $this->files = new Filesystem;
    $this->rootPath = realpath(join_paths(__DIR__, '..', '..'));
    $this->tempPath = join_paths(sys_get_temp_dir(), 'wayfinder-prune-'.uniqid());
});

afterEach(function () {
    $this->files->deleteDirectory($this->tempPath);
});

function generate(object $test, array $options = []): void
{
    $test->artisan('wayfinder:generate', [
        '--path' => $test->tempPath,
        '--app-path' => join_paths($test->rootPath, 'workbench', 'app'),
        '--base-path' => join_paths($test->rootPath, 'workbench'),
        ...$options,
    ])->assertSuccessful();
}

/**
 * Memory limits only mean something in a fresh PHP process, so these runs
 * can't go through artisan() like the rest.
 *
 * @param  list<string>  $phpArgs  Passed to PHP itself, ahead of the script.
 * @param  array<string, string>  $env  Added to the environment it inherits.
 */
function runGenerateProcess(object $test, array $phpArgs = [], array $env = []): Process
{
    $process = new Process([
        PHP_BINARY,
        ...$phpArgs,
        join_paths($test->rootPath, 'vendor', 'bin', 'testbench'),
        'wayfinder:generate',
        '--path='.$test->tempPath,
        '--app-path='.join_paths($test->rootPath, 'workbench', 'app'),
        '--base-path='.join_paths($test->rootPath, 'workbench'),
    ], $test->rootPath, ['WAYFINDER_CACHE_ENABLED' => 'false', ...$env]);

    $process->setTimeout(60);
    $process->run();

    return $process;
}

function outputOf(Process $process): string
{
    return $process->getErrorOutput().$process->getOutput();
}

/**
 * Run raiseMemoryLimit() against a starting limit, optionally with one
 * configured, and report where it left it. Every value has to be above
 * what the suite is already using, or PHP refuses it.
 */
function limitAfterRaising(string $start, ?string $configured = null): string
{
    $original = ini_get('memory_limit');

    try {
        ini_set('memory_limit', $start);

        $command = (new ReflectionClass(GenerateCommand::class))->newInstanceWithoutConstructor();

        (new ReflectionProperty($command, 'config'))->setValue(
            $command,
            new Repository(['wayfinder' => ['memory_limit' => $configured]]),
        );

        (new ReflectionMethod($command, 'raiseMemoryLimit'))->invoke($command);

        return (string) ini_get('memory_limit');
    } finally {
        ini_set('memory_limit', $original);
    }
}

test('generated files exist after generate', function () {
    generate($this);

    expect($this->tempPath)->toBeDirectory();
    expect(join_paths($this->tempPath, 'index.ts'))->toBeFile();
    expect($this->files->allFiles($this->tempPath))->not->toBeEmpty();
});

test('stale files are removed while current files are kept', function () {
    generate($this);

    $current = collect($this->files->allFiles($this->tempPath))
        ->map(fn ($file) => $file->getPathname());

    expect($current)->not->toBeEmpty();

    $stale = join_paths($this->tempPath, 'definitely-not-a-real-route.ts');
    $this->files->put($stale, GENERATED_HEADER."\n\nexport const stale = true\n");
    expect($stale)->toBeFile();

    generate($this);

    expect($stale)->not->toBeFile();
    $current->each(fn ($path) => expect($path)->toBeFile());
});

test('empty directories are pruned', function () {
    generate($this);

    $orphanDir = join_paths($this->tempPath, 'orphan-dir');
    $this->files->ensureDirectoryExists($orphanDir);
    $this->files->put(join_paths($orphanDir, 'thing.ts'), GENERATED_HEADER."\n\nexport const stale = true\n");

    generate($this);

    expect($orphanDir)->not->toBeDirectory();
});

test('helper index is skipped when contents match', function () {
    generate($this);

    $destination = join_paths($this->tempPath, 'index.ts');
    $beforeMtime = filemtime($destination);

    clearstatcache(true, $destination);
    sleep(1);

    generate($this);

    clearstatcache(true, $destination);
    expect(filemtime($destination))->toBe($beforeMtime);
});

test('unchanged generated files are not rewritten', function () {
    generate($this);

    $sample = collect($this->files->allFiles($this->tempPath))
        ->map(fn ($file) => $file->getPathname())
        ->first(fn ($path) => str_ends_with($path, '.ts') && ! str_ends_with($path, 'index.ts'));

    expect($sample)->not->toBeNull();

    $beforeMtime = filemtime($sample);

    clearstatcache(true, $sample);
    sleep(1);

    generate($this);

    clearstatcache(true, $sample);
    expect(filemtime($sample))->toBe($beforeMtime);
});

test('generate completes under a low memory limit', function () {
    // A cold cache needs more than PHP's 128M default (laravel/wayfinder#167).
    // 64M rather than 128M so the two ways this can stop testing anything
    // stay far off: booting far enough to raise the limit takes ~32M, and
    // an unraised run needs ~160M.
    $process = runGenerateProcess($this, ['-d', 'memory_limit=64M']);

    expect($process->isSuccessful())->toBeTrue('wayfinder:generate failed under a 64M memory limit: '.outputOf($process));
    expect(join_paths($this->tempPath, 'index.ts'))->toBeFile();
});

test('a capped memory limit is raised to a bound', function () {
    // Not removed: a runaway analysis should still stop with a PHP error
    // rather than being killed by the OS without one.
    expect(limitAfterRaising('256M'))->toBe('1536M');
});

test('a memory limit above the bound is left alone', function () {
    expect(limitAfterRaising('2048M'))->toBe('2048M');
});

test('an uncapped memory limit is left alone', function () {
    expect(limitAfterRaising('-1'))->toBe('-1');
});

test('a configured limit is used above the bound', function () {
    expect(limitAfterRaising('256M', '4096M'))->toBe('4096M');
});

test('a configured limit is used below the bound', function () {
    // Someone who has named a limit has overridden the bound, not asked to
    // be raised to it.
    expect(limitAfterRaising('512M', '256M'))->toBe('256M');
});

test('a configured limit can remove the cap', function () {
    expect(limitAfterRaising('256M', '-1'))->toBe('-1');
});

test('a configured limit php rejects falls back to the bound', function () {
    expect(limitAfterRaising('256M', 'not-a-size'))->toBe('1536M');
});

test('a rejected configured limit is reported and generation continues', function () {
    $process = runGenerateProcess(
        $this,
        ['-d', 'memory_limit=128M'],
        ['WAYFINDER_MEMORY_LIMIT' => 'not-a-size'],
    );

    $output = outputOf($process);

    expect($process->isSuccessful())->toBeTrue('wayfinder:generate failed: '.$output);
    expect($output)->toContain('not-a-size');
    expect(join_paths($this->tempPath, 'index.ts'))->toBeFile();
});

test('noop regenerate does not touch any file', function () {
    generate($this);

    $before = collect($this->files->allFiles($this->tempPath))
        ->mapWithKeys(fn ($file) => [$file->getPathname() => filemtime($file->getPathname())]);

    expect($before)->not->toBeEmpty();

    clearstatcache();
    sleep(1);

    generate($this);

    clearstatcache();
    $after = collect($this->files->allFiles($this->tempPath))
        ->mapWithKeys(fn ($file) => [$file->getPathname() => filemtime($file->getPathname())]);

    expect($before->keys()->sort()->values()->all())->toBe($after->keys()->sort()->values()->all());

    $changed = $before->filter(fn ($mtime, $path) => $after->get($path) !== $mtime);

    expect($changed->keys()->all())->toBeEmpty(
        'expected no files to be rewritten on a no-op regen, got: '.$changed->keys()->implode(', ')
    );
});

test('files without the generated header are kept', function () {
    generate($this);

    $own = join_paths($this->tempPath, 'local', 'helpers.ts');
    $this->files->ensureDirectoryExists(dirname($own));
    $this->files->put($own, "export const mine = true\n");

    generate($this);

    expect($own)->toBeFile();
});

test('deprecated options warn and still generate', function () {
    $options = ['skip-actions', 'skip-routes', 'skip-database', 'with-form'];

    $command = $this->artisan('wayfinder:generate', [
        '--path' => $this->tempPath,
        '--app-path' => join_paths($this->rootPath, 'workbench', 'app'),
        '--base-path' => join_paths($this->rootPath, 'workbench'),
        ...collect($options)->mapWithKeys(fn ($option) => ["--{$option}" => true])->all(),
    ]);

    foreach ($options as $option) {
        $command->expectsOutputToContain("--{$option} option is deprecated");
    }

    $command->assertSuccessful()->run();

    expect(join_paths($this->tempPath, 'index.ts'))->toBeFile();
});

test('inertia config augmentation can be turned off', function () {
    generate($this);
    expect(join_paths($this->tempPath, 'inertia-config.d.ts'))->toBeFile();

    config()->set('wayfinder.generate.inertia.config', false);

    generate($this);

    expect(join_paths($this->tempPath, 'inertia-config.d.ts'))->not->toBeFile();
    expect($this->files->get(join_paths($this->tempPath, 'types.d.ts')))->toContain('export type SharedData');
});

test('echo events augment the global events interface', function () {
    $packageJson = join_paths($this->rootPath, 'vendor', 'orchestra', 'testbench-core', 'laravel', 'package.json');
    $original = $this->files->exists($packageJson) ? $this->files->get($packageJson) : null;

    $this->files->put($packageJson, json_encode(['dependencies' => ['@laravel/echo-vue' => '*']]));

    try {
        generate($this);
    } finally {
        $original === null ? $this->files->delete($packageJson) : $this->files->put($packageJson, $original);
    }

    $echo = $this->files->get(join_paths($this->tempPath, 'echo-broadcast-events.d.ts'));

    expect($echo)
        ->toContain('declare global {')
        ->toContain('export {};')
        ->not->toContain('declare module')
        ->toContain('".App\\\\Events\\\\OrderShipped": { orderId: number, trackingNumber: string, carrier: string }')
        ->toContain('".server.provisioned": { serverId: number, ip: string }')
        ->not->toContain('BaseServerEvent');
});
